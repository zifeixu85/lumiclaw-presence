export const LIVE_SUBMISSION_IMPORT_OUTCOMES = Object.freeze([
  'LIVE_SUBMISSION_TICKET_REJECTED',
  'LIVE_SUBMISSION_ETAG_CONFLICT',
  'LIVE_SUBMISSION_REQUEST_CONTRACT_INVALID',
  'LIVE_SUBMISSION_QUARANTINED',
  'LIVE_SUBMISSION_DOMAIN_INVARIANT_INVALID',
  'LIVE_SUBMISSION_PERSISTENCE_UNAVAILABLE',
  'LIVE_SUBMISSION_IMPORT_UNCLASSIFIED'
]);

const outcomes = new Set(LIVE_SUBMISSION_IMPORT_OUTCOMES);
const ticketCodes = new Set([
  'LIVE_RUNTIME_ACTION_NOT_READY', 'LIVE_RUNTIME_BINDING_INVALID', 'LIVE_RUNTIME_TASK_SCOPE_INVALID',
  'LIVE_RUNTIME_TICKET_REQUIRED', 'LIVE_RUNTIME_TICKET_EXPIRED_OR_UNKNOWN', 'LIVE_RUNTIME_TICKET_REUSED', 'LIVE_RUNTIME_TICKET_SCOPE_MISMATCH',
  'LIVE_RUNTIME_BOOTSTRAP_REQUIRED', 'LIVE_RUNTIME_BOOTSTRAP_INVALID', 'LIVE_RUNTIME_BOOTSTRAP_UNAVAILABLE', 'LIVE_RUNTIME_AUTH_FAILED'
]);
const etagCodes = new Set(['ETAG_REQUIRED', 'MISSION_VERSION_CONFLICT']);
const requestCodes = new Set(['RUNTIME_EVENT_SCHEMA_INVALID']);
const quarantineCodes = new Set(['RUNTIME_SUBMISSION_QUARANTINED', 'RUNTIME_SUBMISSION_QUARANTINED_REPLAYED']);
const domainCodes = new Set([
  'MISSION_STATE_CONFLICT', 'RUNTIME_FROZEN_FAULT_INVALID', 'RUNTIME_REVISION_SET_INVALID', 'RUNTIME_SOURCE_REVISION_MISMATCH',
  'RUNTIME_AUDIT_SET_INVALID', 'RUNTIME_AUDIT_REVISION_MISMATCH', 'RUNTIME_CORRECTION_BINDING_INVALID', 'RUNTIME_CORRECTION_SOURCE_INVALID',
  'RUNTIME_REAUDIT_BINDING_INVALID', 'TASK_INPUT_PROJECTION_BINDING_MISMATCH', 'TASK_INPUT_PROJECTION_NOT_READY',
  'TASK_INPUT_PROJECTION_PREREQUISITE_MISSING', 'TASK_NOT_FOUND', 'TASK_PREREQUISITE_NOT_ACCEPTED'
]);

export function isLiveSubmissionImportOutcome(value) { return typeof value === 'string' && outcomes.has(value); }

export function classifyLiveSubmissionImportOutcome(status, apiCode) {
  if (status === null || status === undefined || status === 503 || apiCode === 'CONTROL_PLANE_UNAVAILABLE') return 'LIVE_SUBMISSION_PERSISTENCE_UNAVAILABLE';
  if (ticketCodes.has(apiCode)) return 'LIVE_SUBMISSION_TICKET_REJECTED';
  if (etagCodes.has(apiCode)) return 'LIVE_SUBMISSION_ETAG_CONFLICT';
  if (requestCodes.has(apiCode)) return 'LIVE_SUBMISSION_REQUEST_CONTRACT_INVALID';
  if (quarantineCodes.has(apiCode)) return 'LIVE_SUBMISSION_QUARANTINED';
  if (domainCodes.has(apiCode)) return 'LIVE_SUBMISSION_DOMAIN_INVARIANT_INVALID';
  return 'LIVE_SUBMISSION_IMPORT_UNCLASSIFIED';
}
